-- ============================================================================
-- WellPeps Pulse: review desk APIs, equivalent to SQLite migration v9
-- (harvey/state.py MIGRATIONS). Apply after 0004; safe to re-run (idempotent).
--
-- * knowledge_docs: reference documents uploaded in the dashboard. kind /
--   authority / programs_json steer how the drafter uses them; status is
--   in_review until an admin approves (active), or rejected / superseded.
--   text is the extracted text; extraction is done | pending (no PDF reader
--   installed on the server) | empty.
-- * community_permissions: what a human recorded about a community's rules
--   (brand_participation allowed | not_allowed | unknown, links_allowed
--   'true' | 'false' | 'unknown'). harvey/communities.py overlays it on
--   config/communities.yaml; the recorded value wins.
--
-- New tables, so this file enables RLS, grants pulse_app and adds its
-- allow-all policy (the 0001 loops only covered the tables that existed then).
-- ============================================================================

create table if not exists pulse.knowledge_docs (
    id bigint generated by default as identity primary key,
    filename text not null,
    kind text not null default 'other',
    authority text not null default 'reference',
    programs_json text not null default '[]',
    approved_by text not null default '',
    effective_date text not null default '',
    supersedes_id bigint references pulse.knowledge_docs (id),
    note text not null default '',
    status text not null default 'in_review',   -- in_review | active | rejected | superseded
    text text not null default '',
    extraction text not null default 'done',    -- done | pending | empty
    size_bytes integer not null default 0,
    uploaded_by text not null default '',
    created_at timestamp default (now() at time zone 'utc'),
    decided_by text not null default '',
    decided_at timestamp
);
create index if not exists idx_knowledge_docs_status on pulse.knowledge_docs (status, id);

create table if not exists pulse.community_permissions (
    community_id text primary key,
    brand_participation text not null default 'unknown',
    links_allowed text not null default 'unknown',
    moderator_contact text not null default '',
    note text not null default '',
    recorded_by text not null default '',
    recorded_at timestamp default (now() at time zone 'utc')
);

-- ── Security (same model as 0001) ────────────────────────────────────────

alter table pulse.knowledge_docs enable row level security;
alter table pulse.community_permissions enable row level security;

revoke all on pulse.knowledge_docs from public;
revoke all on pulse.community_permissions from public;
revoke all on sequence pulse.knowledge_docs_id_seq from public;

do $$
declare
    api_role text;
begin
    foreach api_role in array array['anon', 'authenticated'] loop
        if exists (select 1 from pg_roles where rolname = api_role) then
            execute format('revoke all on pulse.knowledge_docs from %I', api_role);
            execute format('revoke all on pulse.community_permissions from %I', api_role);
            execute format('revoke all on sequence pulse.knowledge_docs_id_seq from %I', api_role);
        end if;
    end loop;
end
$$;

grant select, insert, update, delete on pulse.knowledge_docs to pulse_app;
grant select, insert, update, delete on pulse.community_permissions to pulse_app;
grant usage, select on sequence pulse.knowledge_docs_id_seq to pulse_app;

do $$
declare
    tbl text;
begin
    foreach tbl in array array['knowledge_docs', 'community_permissions'] loop
        execute format('drop policy if exists pulse_app_all on pulse.%I', tbl);
        execute format(
            'create policy pulse_app_all on pulse.%I for all to pulse_app using (true) with check (true)',
            tbl);
    end loop;
end
$$;

-- ── Version ──────────────────────────────────────────────────────────────

insert into pulse.schema_version (version, description)
values (9, '0005_review_desk: SQLite migration v9')
on conflict (version) do nothing;
